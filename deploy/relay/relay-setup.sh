#!/usr/bin/env bash
# Turn a fresh Ubuntu VPS into a Paydar relay: pure nftables DNAT + masquerade to the backend.
# Run as root ON the relay. Idempotent: safe to re-run on an existing relay.
#
#   ssh root@NEW_IP "PUBKEY='$(cat ~/.ssh/id_ed25519.pub)' bash -s" < relay-setup.sh
#
# Env:
#   PUBKEY   ssh public key to authorize for root (required unless a key is already present)
#   BACKEND  backend IP (default 79.127.32.253, Ubuntu26-VPN)
#   CHECK=1  only print the generated nftables config, change nothing
set -euo pipefail

BACKEND="${BACKEND:-79.127.32.253}"
WAN="$(ip -4 route show default | awk '{print $5; exit}')"
[ -n "$WAN" ] || { echo "no default route / WAN interface found" >&2; exit 1; }

# Keep in sync with the inbound ports on the backend (Marzban VLESS + OpenGate).
NFT_CONF=$(cat <<NFT
#!/usr/sbin/nft -f
# Paydar relay: forward Marzban + OpenGate traffic to Ubuntu26-VPN ($BACKEND)
# Generated by deploy/relay/relay-setup.sh -- edit the script, not this file.
flush ruleset

define BACKEND = $BACKEND
define WAN = "$WAN"
# Marzban: haproxy 443 + direct VLESS inbounds
define MARZBAN_TCP = { 443, 2094-2097, 3098, 3099, 3457, 3821, 4275, 4506, 4712, 4938, 5217, 5690, 5836, 6291, 6382, 6704, 7124, 7459, 7938, 8106, 8563, 9143, 12094-12097, 13098, 13099, 13457, 13821, 14275, 14506, 14712, 14938, 15217, 15690, 15836, 16291, 16382, 17124, 17459, 17938, 18106, 18563, 19143 }
# OpenGate: panel + client port range
define OPENGATE_TCP = { 21714, 62000-64000 }
define OPENGATE_UDP = { 62000-64000 }
# OpenGate classic VPNs: IPsec IKE/NAT-T + L2TP (UDP), PPTP control (TCP); GRE/ESP below
define CLASSIC_UDP = { 500, 4500, 1701 }
define CLASSIC_TCP = { 1723 }

table inet filter {
  chain input {
    type filter hook input priority 0; policy drop;
    iif lo accept
    ct state established,related accept
    ct state invalid drop
    meta l4proto { icmp, ipv6-icmp } accept
    tcp dport 22 accept
  }
  chain forward {
    type filter hook forward priority 0; policy drop;
    ct state established,related accept
    ct status dnat accept
  }
  chain output {
    type filter hook output priority 0; policy accept;
  }
}

table ip relay {
  # PPTP needs the conntrack helper so GRE call IDs are tracked through the NAT
  ct helper pptp-h {
    type "pptp" protocol tcp;
    l3proto ip;
  }
  chain helpers {
    type filter hook prerouting priority filter; policy accept;
    iifname \$WAN tcp dport 1723 ct helper set "pptp-h"
  }
  chain prerouting {
    type nat hook prerouting priority dstnat; policy accept;
    iifname \$WAN tcp dport \$MARZBAN_TCP dnat to \$BACKEND
    iifname \$WAN tcp dport \$OPENGATE_TCP dnat to \$BACKEND
    iifname \$WAN udp dport \$OPENGATE_UDP dnat to \$BACKEND
    iifname \$WAN udp dport \$CLASSIC_UDP dnat to \$BACKEND
    iifname \$WAN tcp dport \$CLASSIC_TCP dnat to \$BACKEND
    iifname \$WAN ip protocol { gre, esp } dnat to \$BACKEND
  }
  chain postrouting {
    type nat hook postrouting priority srcnat; policy accept;
    oifname \$WAN ip daddr \$BACKEND ct status dnat masquerade
  }
}
NFT
)

if [ "${CHECK:-0}" = 1 ]; then
  printf '%s\n' "$NFT_CONF"
  exit 0
fi

[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
echo "== relay setup: WAN=$WAN BACKEND=$BACKEND"

# 1. SSH key first, so turning off password auth can't lock us out.
install -d -m 700 /root/.ssh
touch /root/.ssh/authorized_keys && chmod 600 /root/.ssh/authorized_keys
if [ -n "${PUBKEY:-}" ] && ! grep -qF "$PUBKEY" /root/.ssh/authorized_keys; then
  echo "$PUBKEY" >> /root/.ssh/authorized_keys
  echo "   key added"
fi
if grep -qE '^(ssh-|ecdsa-)' /root/.ssh/authorized_keys; then
  cat > /etc/ssh/sshd_config.d/00-relay-hardening.conf <<'C'
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin prohibit-password
MaxAuthTries 3
C
  sshd -t && systemctl reload ssh
  echo "   ssh: key-only"
else
  echo "   WARNING: no authorized key, leaving password auth on" >&2
fi

# 2. Kernel: forwarding, BBR, conntrack sized for ~1k users.
cat > /etc/sysctl.d/90-relay.conf <<'SYS'
net.ipv4.ip_forward = 1
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr
net.netfilter.nf_conntrack_max = 262144
net.netfilter.nf_conntrack_tcp_timeout_established = 7200
net.netfilter.nf_conntrack_udp_timeout_stream = 180
net.ipv4.conf.all.rp_filter = 2
net.ipv4.conf.default.rp_filter = 2
net.core.rmem_max = 16777216
net.core.wmem_max = 16777216
net.core.netdev_max_backlog = 16384
SYS
printf "nf_conntrack\nnf_conntrack_pptp\nnf_nat_pptp\n" > /etc/modules-load.d/conntrack.conf
echo 'options nf_conntrack hashsize=65536' > /etc/modprobe.d/conntrack.conf
modprobe nf_conntrack; modprobe nf_conntrack_pptp; modprobe nf_nat_pptp 2>/dev/null || true
echo 65536 > /sys/module/nf_conntrack/parameters/hashsize 2>/dev/null || true
sysctl -q -p /etc/sysctl.d/90-relay.conf

# 3. Firewall: ufw would fight with our ruleset.
command -v ufw >/dev/null && ufw disable >/dev/null 2>&1 || true
command -v nft >/dev/null || { apt-get update -qq && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nftables; }
[ -f /etc/nftables.conf ] && cp -a /etc/nftables.conf "/root/nftables.conf.bak-$(date +%Y%m%d-%H%M%S)"
printf '%s\n' "$NFT_CONF" > /etc/nftables.conf
nft -c -f /etc/nftables.conf
nft -f /etc/nftables.conf
systemctl enable nftables >/dev/null 2>&1

# 4. Self-check: backend reachable on 443 from here.
if timeout 5 bash -c "exec 3<>/dev/tcp/$BACKEND/443" 2>/dev/null; then
  echo "   backend $BACKEND:443 reachable"
else
  echo "   WARNING: backend $BACKEND:443 NOT reachable from this relay" >&2
fi
echo "== done: $(nft list table ip relay | grep -c 'dnat to') dnat rules, ip_forward=$(sysctl -n net.ipv4.ip_forward)"
